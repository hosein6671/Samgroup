// Regenerates apps/web/src/features/home/world-land.ts — the land mask behind the Home page's
// export map — from Natural Earth's 1:110m land polygons.
//
// Natural Earth is public domain (https://www.naturalearthdata.com/about/terms-of-use/). The
// source file is not committed; download it, then run:
//
//   curl -L -o ne_110m_land.geojson \
//     https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
//   node scripts/build-world-land-mask.mjs ne_110m_land.geojson
//
// The mask is 1° cells over the map's own frame (longitude −180…180, latitude 80…−58): a cell is
// land when any of four sample points inside it falls on land, which keeps narrow coasts — Italy,
// the shores of the Red Sea and the Gulf — instead of dropping them.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const [geojsonPath] = process.argv.slice(2);
if (!geojsonPath) {
  console.error("usage: node scripts/build-world-land-mask.mjs <ne_110m_land.geojson>");
  process.exit(64);
}

const LON0 = -180;
const LAT1 = 80;
const LAT0 = -58;
const COLS = 360;
const ROWS = LAT1 - LAT0;

const geo = JSON.parse(fs.readFileSync(geojsonPath, "utf8"));
const polygons = geo.features.flatMap((feature) =>
  feature.geometry.type === "Polygon"
    ? [feature.geometry.coordinates]
    : feature.geometry.type === "MultiPolygon"
      ? feature.geometry.coordinates
      : [],
);

const inRing = (lon, lat, ring) => {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
const onLand = (lon, lat) =>
  polygons.some(
    ([outer, ...holes]) => inRing(lon, lat, outer) && !holes.some((hole) => inRing(lon, lat, hole)),
  );

const SAMPLES = [
  [0.25, 0.25],
  [0.75, 0.25],
  [0.25, 0.75],
  [0.75, 0.75],
];
const bits = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
let land = 0;
for (let row = 0; row < ROWS; row++) {
  for (let col = 0; col < COLS; col++) {
    const lon = LON0 + col;
    const lat = LAT1 - row;
    if (SAMPLES.some(([dx, dy]) => onLand(lon + dx, lat - dy))) {
      const index = row * COLS + col;
      bits[index >> 3] |= 1 << (index & 7);
      land++;
    }
  }
}

const base64 = Buffer.from(bits).toString("base64");
const lines = base64.match(/.{1,96}/g) ?? [];
const out = `/**
 * Where there is land, for the Home page's export map — 1° cells from Natural Earth's 1:110m land
 * polygons (public domain, https://www.naturalearthdata.com). Generated by
 * \`scripts/build-world-land-mask.mjs\`; do not edit by hand.
 *
 * The frame is the map's own: longitude ${LON0}…180, latitude ${LAT1}…${LAT0}, ${COLS} × ${ROWS} cells, row by row from
 * the north-west, one bit per cell (least significant first). ${land} of ${COLS * ROWS} cells are land.
 */

const COLS = ${COLS};
const ROWS = ${ROWS};
const LON0 = ${LON0};
const LAT1 = ${LAT1};

const MASK =
${lines.map((line) => `  "${line}"`).join(" +\n")};

let bits: Uint8Array | null = null;

function decode(): Uint8Array {
  const raw = atob(MASK);
  const out = new Uint8Array(raw.length);
  for (let i = 0; i < raw.length; i++) out[i] = raw.charCodeAt(i);
  return out;
}

/** Whether the point lies in a land cell. Points outside the frame are sea. */
export function isLand(lon: number, lat: number): boolean {
  const col = Math.floor(lon - LON0);
  const row = Math.floor(LAT1 - lat);
  if (col < 0 || col >= COLS || row < 0 || row >= ROWS) return false;
  bits ??= decode();
  const index = row * COLS + col;
  return ((bits[index >> 3] ?? 0) >> (index & 7)) % 2 === 1;
}
`;

const target = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "../apps/web/src/features/home/world-land.ts",
);
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(process.cwd(), target)}: ${land} land cells of ${COLS * ROWS}`);
